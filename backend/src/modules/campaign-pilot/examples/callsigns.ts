// Функция для получения случайного позывного из любой категории
export function getRandomCallsign(): string {
  const allCallsigns = Object.values(BATTLE_TECH_CALLSIGNS).flat();
  return allCallsigns[Math.floor(Math.random() * allCallsigns.length)];
}

// Функция для получения позывного из конкретной категории
export function getCallsignByCategory(category: keyof typeof BATTLE_TECH_CALLSIGNS): string {
  const callsigns = BATTLE_TECH_CALLSIGNS[category];
  return callsigns[Math.floor(Math.random() * callsigns.length)];
}

// Функция для получения позывного, подходящего для фракции
export function getFactionThemedCallsign(factionName: string): string {
  const factionLower = factionName.toLowerCase();
  
  if (factionLower.includes('steiner') || factionLower.includes('lyran')) {
    // Steiner - немецкие/европейские темы
    return getCallsignByCategory('MYTHOLOGICAL');
  } else if (factionLower.includes('davion') || factionLower.includes('federated')) {
    // Davion - рыцарские/благородные темы
    return getCallsignByCategory('CHARACTER_THEMED');
  } else if (factionLower.includes('kurita') || factionLower.includes('draconis')) {
    // Kurita - японские/восточные темы
    return getCallsignByCategory('NATURE_THEMED');
  } else if (factionLower.includes('liao') || factionLower.includes('capellan')) {
    // Liao - китайские/азиатские темы
    return getCallsignByCategory('SPACE_THEMED');
  } else if (factionLower.includes('marik') || factionLower.includes('free worlds')) {
    // Marik - средиземноморские/греческие темы
    return getCallsignByCategory('WEAPON_THEMED');
  } else {
    // По умолчанию
    return getRandomCallsign();
  }
}
